const { contextBridge, ipcRenderer, webUtils } = require("electron");

contextBridge.exposeInMainWorld("rasputim", {
  getState: () => ipcRenderer.invoke("state:get"),
  authStatus: () => ipcRenderer.invoke("auth:status"),
  setupAccount: (payload) => ipcRenderer.invoke("auth:setup", payload),
  login: (payload) => ipcRenderer.invoke("auth:login", payload),
  logout: () => ipcRenderer.invoke("auth:logout"),
  enableSharedUserDirectory: () => ipcRenderer.invoke("auth:enable-shared-directory"),
  connectSharedUserDirectory: () => ipcRenderer.invoke("auth:connect-shared-directory"),
  useLocalUserDirectory: () => ipcRenderer.invoke("auth:use-local-directory"),
  createUser: (payload) => ipcRenderer.invoke("auth:create-user", payload),
  updateUser: (id, payload) => ipcRenderer.invoke("auth:update-user", id, payload),
  resetUserPassword: (id, password) => ipcRenderer.invoke("auth:reset-user-password", id, password),
  addTool: (payload) => ipcRenderer.invoke("tools:add", payload),
  checkoutTool: (payload) => ipcRenderer.invoke("tools:checkout", payload),
  returnTool: (payload) => ipcRenderer.invoke("tools:return", payload),
  setToolStatus: (id, payload) => ipcRenderer.invoke("tools:set-status", id, payload),
  removeTool: (id) => ipcRenderer.invoke("tools:remove", id),
  getAppInfo: () => ipcRenderer.invoke("app:info"),
  getLocalAiStatus: () => ipcRenderer.invoke("ai:status"),
  askLocalAi: (prompt, model) => ipcRenderer.invoke("ai:chat", { prompt, model }),
  createPcpProject: (payload) => ipcRenderer.invoke("pcp:create", payload),
  updatePcpProject: (id, payload) => ipcRenderer.invoke("pcp:update", id, payload),
  transitionPcpProject: (id, payload) => ipcRenderer.invoke("pcp:transition", id, payload),
  blockPcpProject: (id, payload) => ipcRenderer.invoke("pcp:block", id, payload),
  archivePcpProject: (id, payload) => ipcRenderer.invoke("pcp:archive", id, payload),
  choosePcpSharedDirectory: (stationName) => ipcRenderer.invoke("pcp:choose-shared-directory", stationName),
  useLocalPcp: (stationName) => ipcRenderer.invoke("pcp:use-local", stationName),
  updatePcpStation: (stationName) => ipcRenderer.invoke("pcp:update-station", stationName),
  refreshPcp: () => ipcRenderer.invoke("pcp:refresh"),
  chooseProjects: () => ipcRenderer.invoke("dialog:projects"),
  analyzeProjects: (paths) => ipcRenderer.invoke("projects:analyze", paths),
  removeProject: (id) => ipcRenderer.invoke("projects:remove", id),
  revealProject: (id) => ipcRenderer.invoke("projects:reveal", id),
  chooseSalesFile: () => ipcRenderer.invoke("dialog:sales"),
  importSales: (filePath) => ipcRenderer.invoke("sales:import", filePath),
  chooseStockFile: () => ipcRenderer.invoke("dialog:stock"),
  previewStock: (filePath, mode) => ipcRenderer.invoke("procurement:preview-stock", { filePath, mode }),
  applyStockPreview: (previewId, payload) => ipcRenderer.invoke("procurement:apply-stock-preview", previewId, payload),
  cancelStockPreview: (previewId) => ipcRenderer.invoke("procurement:cancel-stock-preview", previewId),
  setInvoiceStatus: (number, status) => ipcRenderer.invoke("procurement:invoice-status", number, status),
  recordMovement: (payload) => ipcRenderer.invoke("procurement:record-movement", payload),
  addMaterial: (payload) => ipcRenderer.invoke("procurement:add-material", payload),
  addQuotation: (payload) => ipcRenderer.invoke("procurement:add-quotation", payload),
  getTavilyCredentials: () => ipcRenderer.invoke("market:credentials:get"),
  testTavilyKey: (apiKey) => ipcRenderer.invoke("market:credentials:test", apiKey),
  saveTavilyKey: (apiKey) => ipcRenderer.invoke("market:credentials:save", apiKey),
  removeTavilyKey: () => ipcRenderer.invoke("market:credentials:remove"),
  researchMarket: (materialCode, radiusKm) => ipcRenderer.invoke("market:research", { materialCode, radiusKm }),
  openExternal: (url, purpose, supplierName) => ipcRenderer.invoke("market:open-url", { url, purpose, supplierName }),
  copyMarketPhone: (phoneNumber) => ipcRenderer.invoke("market:copy-phone", phoneNumber),
  exportProjectReport: (id) => ipcRenderer.invoke("report:project", id),
  exportSummaryReport: () => ipcRenderer.invoke("report:summary"),
  clearState: () => ipcRenderer.invoke("state:clear"),
  restoreDemo: () => ipcRenderer.invoke("state:restore-demo"),
  pathForFile: (file) => webUtils.getPathForFile(file),
  onAnalysisProgress: (callback) => {
    const listener = (_event, payload) => callback(payload);
    ipcRenderer.on("analysis:progress", listener);
    return () => ipcRenderer.removeListener("analysis:progress", listener);
  },
  onPcpChanged: (callback) => {
    const listener = (_event, payload) => callback(payload);
    ipcRenderer.on("pcp:changed", listener);
    return () => ipcRenderer.removeListener("pcp:changed", listener);
  },
  minimize: () => ipcRenderer.invoke("window:minimize"),
  toggleMaximize: () => ipcRenderer.invoke("window:toggle-maximize"),
  close: () => ipcRenderer.invoke("window:close"),
});
